namespace NotificationService.Persistence.Inbox;

/// <summary>
/// Отметка о том, что событие уже обработано (паттерн inbox). Нужна, потому что RabbitMQ
/// доставляет at-least-once: и переотправка после падения консьюмера до ack, и повторная
/// публикация из чужого outbox (там та же гарантия) приведут к тому же сообщению второй раз,
/// а второе письмо об одном событии клиент воспринимает как сбой.
/// </summary>
public class InboxMessage
{
    /// <summary>
    /// Идентификатор события из <c>IntegrationEvent.EventId</c>; он же ключ таблицы.
    /// <para>
    /// В чек-листе Фазы 6 этот пункт назван «Inbox по MessageId», но ключом взят именно
    /// <c>EventId</c>: свойство сообщения <c>MessageId</c> проставляют диспетчеры outbox
    /// по соглашению, и лежит в нём их собственный идентификатор строки outbox, а не
    /// идентификатор события. Дедупликация по нему работала бы ровно до первого издателя,
    /// который свойство не выставит (или выставит по-своему), причём молча. <c>EventId</c>
    /// же есть у каждого события по контракту и едет внутри payload.
    /// </para>
    /// </summary>
    public Guid EventId { get; set; }

    /// <summary>Имя типа события — только для разбора инцидентов, в дедупликации не участвует.</summary>
    public string EventType { get; set; } = string.Empty;

    public DateTimeOffset ProcessedAtUtc { get; set; }
}
