namespace NotificationService.Domain.Entities;

/// <summary>
/// Какими каналами клиент согласен получать уведомления.
/// <para>
/// Строки может не быть вовсе — тогда включены все каналы, для которых есть шаблон и контакт
/// (поведение до появления настроек). Молчание трактуется как согласие сознательно: речь про
/// уведомления о собственном грузе, и клиент, ничего не настраивавший, ждёт их получить, а не
/// обнаружить, что перевозчик молчал.
/// </para>
/// <para>
/// Каналы перечислены полями, а не набором значений enum: настройка заводится только для канала,
/// которым сервис действительно умеет слать (Push сегодня не умеет — переключатель для него был
/// бы обманом в интерфейсе). Появится отправитель — появится и поле вместе с миграцией.
/// </para>
/// </summary>
public class NotificationPreference
{
    /// <summary>Идентификатор пользователя в identity-service; он же ключ этой таблицы.</summary>
    public Guid UserId { get; set; }

    public bool EmailEnabled { get; set; } = true;
    public bool SmsEnabled { get; set; } = true;
}
