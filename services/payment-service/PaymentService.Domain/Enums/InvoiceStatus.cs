namespace PaymentService.Domain.Enums;

/// <summary>
/// Состояние счёта. Значений пока два: отмена и возврат появятся вместе с обработкой
/// <c>OrderCancelled</c> (задача 5 Фазы 9) — статус хранится в БД строкой, поэтому добавление
/// значения не потребует миграции, и заводить их заранее «на будущее» смысла нет.
/// </summary>
public enum InvoiceStatus
{
    /// <summary>Счёт выставлен, оплата ожидается.</summary>
    Issued = 0,

    /// <summary>Оплата получена полностью.</summary>
    Paid = 1,
}
