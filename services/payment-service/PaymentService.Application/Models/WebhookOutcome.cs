namespace PaymentService.Application.Models;

/// <summary>
/// Что делать с ответом на webhook. Провайдер повторяет доставку на любой не-2xx, поэтому
/// «повторить» и «больше не присылать» — разные исходы, и решать это должен сценарий, а не
/// контроллер.
/// </summary>
public enum WebhookOutcome
{
    /// <summary>Исход платежа записан.</summary>
    Applied = 0,

    /// <summary>
    /// Уведомление принято, но менять нечего: платёж уже в окончательном статусе, ещё ждёт
    /// оплаты или вовсе не наш. Повтор ничего не изменит — провайдеру отвечаем успехом.
    /// </summary>
    Ignored = 1,

    /// <summary>
    /// Помеха на нашей стороне (провайдер недоступен для перепроверки). Повтор имеет смысл —
    /// провайдеру нужно ответить ошибкой, чтобы он прислал уведомление снова.
    /// </summary>
    TemporaryFailure = 2,
}
