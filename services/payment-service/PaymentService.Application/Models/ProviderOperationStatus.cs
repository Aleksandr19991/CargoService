namespace PaymentService.Application.Models;

/// <summary>
/// Статус операции на стороне провайдера — и платежа, и возврата: словарь у них один и тот же,
/// поэтому enum один. Это статус провайдера, а не наш: собственный статус счёта/платежа
/// (сущности Фазы 9) выводится из него бизнес-логикой, а не приравнивается к нему.
/// </summary>
public enum ProviderOperationStatus
{
    /// <summary>Операция заведена, но денег ещё нет — клиент не прошёл оплату.</summary>
    Pending = 0,

    /// <summary>Деньги списаны (или возвращены) — окончательный успех.</summary>
    Succeeded = 1,

    /// <summary>Операция отменена провайдером, банком или клиентом — окончательный отказ.</summary>
    Canceled = 2,
}
